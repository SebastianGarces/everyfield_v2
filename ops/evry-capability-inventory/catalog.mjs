export const domains = [];
export const questions = [];
function domain(id, title, source, current, rows) {
  domains.push({ id, title, source, current });
  rows.forEach(
    ([text, likelihood, shape, toolIds, gap, expected, recipe = null], index) =>
      questions.push({
        id: `${id}-${String(index + 1).padStart(2, "0")}`,
        domain: id,
        turns: Array.isArray(text) ? text : [text],
        likelihood,
        likelihoodBasis: likelihoods[likelihood],
        shape,
        tools: toolIds ? toolIds.split(" ") : [],
        gap,
        expected,
        recipe,
        evaluation: "not_run",
        source,
      })
  );
}

