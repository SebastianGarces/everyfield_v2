#!/usr/bin/env node
// Materialize the Codex adapters whose sources of truth remain in .claude/.
// Run with --write after adding a Claude-native workflow skill or agent; run
// without arguments (or with --check) to verify that the checked-in adapters
// have not drifted.

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import console from "node:console";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const write = process.argv.includes("--write");
const unknown = process.argv
  .slice(2)
  .filter((arg) => !["--write", "--check"].includes(arg));

if (unknown.length > 0) {
  console.error(`unknown argument(s): ${unknown.join(", ")}`);
  process.exit(2);
}

const WORKFLOW_SKILLS = [
  "browser-validation",
  "deliver",
  "dispatch",
  "grilling",
  "open-pr",
  "prototype",
  "requirements-docs",
  "resolving-merge-conflicts",
  "spec-intake",
  "standup",
  "validate",
  "work-overnight",
];

const CUSTOM_AGENTS = ["architect", "backend", "code-reviewer", "frontend"];
const failures = [];

function relative(file) {
  return path.relative(ROOT, file);
}

function ensureLink(destination, source) {
  const target = path.relative(path.dirname(destination), source);

  let stat;
  try {
    stat = fs.lstatSync(destination);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  if (stat?.isSymbolicLink() && fs.readlinkSync(destination) === target) return;

  if (!write) {
    failures.push(`${relative(destination)} must be a symlink to ${target}`);
    return;
  }

  if (stat && !stat.isSymbolicLink()) {
    throw new Error(`refusing to replace non-symlink ${relative(destination)}`);
  }

  if (stat) fs.unlinkSync(destination);
  fs.symlinkSync(target, destination);
}

function ensureSkillLinks(name) {
  const source = path.join(ROOT, ".claude", "skills", name);

  if (!fs.existsSync(path.join(source, "SKILL.md"))) {
    failures.push(`missing source skill: ${relative(source)}`);
    return;
  }

  ensureLink(path.join(ROOT, ".agents", "skills", name), source);
  ensureLink(path.join(ROOT, ".cursor", "skills", name), source);
}

function parseClaudeAgent(name) {
  const source = path.join(ROOT, ".claude", "agents", `${name}.md`);
  const text = fs.readFileSync(source, "utf8");
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
  if (!match) throw new Error(`invalid frontmatter: ${relative(source)}`);

  const field = (key) => {
    const value = new RegExp(`^${key}:\\s*(.+)$`, "m").exec(match[1])?.[1];
    if (!value) throw new Error(`missing ${key}: ${relative(source)}`);
    return value.replace(/^(["'])(.*)\1$/, "$2");
  };

  const body = match[2].trim().replaceAll(".claude/skills/", ".agents/skills/");

  if (body.includes("'''")) {
    throw new Error(
      `${relative(source)} contains TOML literal-string terminator`
    );
  }

  return `# Generated by ops/sync-codex-setup.mjs from .claude/agents/${name}.md.\n# Edit the Claude source, then run: node ops/sync-codex-setup.mjs --write\nname = ${JSON.stringify(field("name"))}\ndescription = ${JSON.stringify(field("description"))}\ndeveloper_instructions = '''\n${body}\n'''\n`;
}

function ensureAgent(name) {
  const destination = path.join(ROOT, ".codex", "agents", `${name}.toml`);
  const expected = parseClaudeAgent(name);
  const actual = fs.existsSync(destination)
    ? fs.readFileSync(destination, "utf8")
    : null;

  if (actual === expected) return;

  if (!write) {
    failures.push(`${relative(destination)} is missing or stale`);
    return;
  }

  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, expected);
}

for (const skill of WORKFLOW_SKILLS) ensureSkillLinks(skill);
for (const agent of CUSTOM_AGENTS) ensureAgent(agent);

if (failures.length > 0) {
  for (const failure of failures) console.error(`codex setup: ${failure}`);
  console.error("Run: node ops/sync-codex-setup.mjs --write");
  process.exit(1);
}

console.log(
  `codex setup: ${WORKFLOW_SKILLS.length} workflow skills and ${CUSTOM_AGENTS.length} custom agents are in sync across Codex and Cursor`
);
